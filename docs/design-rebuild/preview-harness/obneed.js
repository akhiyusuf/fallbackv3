// Onboarding: how much height does each step need below the banner (content + footer), per width and type setting?
// Writes obneed.json, and (given a path) the generated onboardingNeeds.ts the shell reads.
// usage: node obneed.js [path/to/src/features/onboarding/onboardingNeeds.ts] [width ...]
const { chromium } = require('playwright');
const fs = require('fs');
const args = process.argv.slice(2); const tsPath = args[0] && args[0].endsWith('.ts') ? args.shift() : null;
const WIDTHS = args.length ? args.map(Number) : [320, 344, 360, 375, 390, 412, 430];
const DENSITIES = ['tight', 'compact', 'regular'];
const STEPS = ['concept', 'hook', 'types', 'consistency', 'personalize', 'notifications-primer', 'first-task'];
(async () => {
  const browser = await chromium.launch(); const out = {};
  await Promise.all(DENSITIES.map(async (density) => {
    for (const w of WIDTHS) {
      const page = await (await browser.newContext({ viewport: { width: w, height: 900 }, deviceScaleFactor: 1 })).newPage();
      await page.addInitScript((d) => { window.__obDensity = d; }, density);   // the shell obeys this instead of choosing
      await page.goto('http://localhost:8767/', { waitUntil: 'load' }); await page.waitForTimeout(2500);
      const row = [];
      for (const step of STEPS) {
        await page.evaluate((p) => window.__fallbackPreview.go(p), '/onboarding/' + step); await page.waitForTimeout(900);
        row.push(await page.evaluate(() => {
          const els = [...document.querySelectorAll('*')].filter((e) => { const cs = getComputedStyle(e); const b = e.getBoundingClientRect(); return (cs.overflowY === 'auto' || cs.overflowY === 'scroll') && b.width > 200 && b.height > 0 && e.offsetParent !== null && b.left >= 0 && b.left < innerWidth; });
          const e = els[els.length - 1]; const root = e.parentElement; const foot = root.lastElementChild.getBoundingClientRect().height;
          return Math.ceil(e.scrollHeight + foot);
        }));
      }
      (out[density] = out[density] || {})[w] = row; console.log(density, w, row.join(' '));
      await page.context().close();
    }
  }));
  fs.writeFileSync(__dirname + '/obneed.json', JSON.stringify(out));
  if (tsPath) {
    let ts = "/**\n * GENERATED by docs/design-rebuild/preview-harness/obneed.js. Do not edit by hand.\n * The height each onboarding step needs below the banner (words, example, buttons) at each type\n * setting. Rows are [from this screen width, step 1, step 2, ... step 7]; a narrower screen wraps more.\n */\nimport type { OnboardingDensity } from './OnboardingShell';\n\nexport const ONBOARDING_NEEDS: Record<OnboardingDensity, readonly (readonly number[])[]> = {\n";
    for (const d of DENSITIES) {
      ts += `  ${d}: [\n`; let prev = null;
      for (const w of WIDTHS) { const r = out[d][w]; if (JSON.stringify(r) !== prev) { ts += `    [${[prev === null ? 0 : w, ...r].join(', ')}],\n`; prev = JSON.stringify(r); } }
      ts += '  ],\n';
    }
    fs.writeFileSync(tsPath, ts + '};\n'); console.log('wrote', tsPath);
  }
  await browser.close();
})();
