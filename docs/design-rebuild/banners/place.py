"""Write src/features/onboarding/bannerImages.ts for the browser preview from the chosen cut-outs.
Usage: python3 place.py <path to bannerImages.ts> 1=banner_1.png 2=dl/banner_2_b.png ...
Each cut-out is saved as chosen/banner_<step>.png and .webp (640 px on its long side at most 960 wide), and inlined.
The app should bundle the files as assets instead of inlining them."""
import base64, os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__)); out = os.path.join(here, 'chosen'); os.makedirs(out, exist_ok=True)
rows = []
for arg in sys.argv[2:]:
    step, src = arg.split('='); src = os.path.join(here, src)
    png = os.path.join(out, f'banner_{step}.png'); webp = os.path.join(out, f'banner_{step}.webp')
    if os.path.abspath(src) != os.path.abspath(png): subprocess.run(['cp', src, png], check=True)
    subprocess.run(['convert', png, '-resize', '960x640>', '-quality', '86', webp], check=True)
    rows.append((int(step), base64.b64encode(open(webp, 'rb').read()).decode(), os.path.getsize(webp)))
lines = ['/**', ' * Banner pictures for the onboarding steps (AI-made clay renders, cut out so the banner colour shows through).',
         ' * A step with no entry keeps its drawn stand-in. GENERATED by docs/design-rebuild/banners/place.py for the browser',
         ' * preview, which inlines the files; the app should bundle them as assets.', ' */',
         "import type { ImageSourcePropType } from 'react-native';", '', 'export type OnboardingStep = 1 | 2 | 3 | 4 | 5 | 6 | 7;', '', '/* eslint-disable */',
         'export const BANNER_IMAGES: Partial<Record<OnboardingStep, ImageSourcePropType>> = {']
for step, b64, _ in sorted(rows): lines.append(f"  {step}: {{ uri: 'data:image/webp;base64,{b64}' }},")
lines += ['};', '']
open(sys.argv[1], 'w').write('\n'.join(lines))
print(', '.join(f'{s}: {round(n/1024)} KB' for s, _, n in sorted(rows)))
