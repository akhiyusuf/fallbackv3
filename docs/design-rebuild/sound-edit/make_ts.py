"""Write src/services/sfx/sounds.generated.ts for the browser preview from out/*.wav.
Usage: python3 make_ts.py <path to src/services/sfx/sounds.generated.ts>
The preview inlines the audio so it stays one file. The app should bundle the WAVs as assets instead."""
import base64, glob, os, sys
here = os.path.dirname(os.path.abspath(__file__))
lines = ['/** GENERATED by the sound edit (docs/design-rebuild/sound-edit/edit.py). Do not edit by hand. */', '/* eslint-disable */', 'export const SOUND_DATA = {']
for p in sorted(glob.glob(os.path.join(here, 'out', '*.wav'))):
    name = os.path.splitext(os.path.basename(p))[0]
    lines.append(f"  {name}: 'data:audio/wav;base64,{base64.b64encode(open(p, 'rb').read()).decode()}',")
lines += ['} as const;', '']
open(sys.argv[1], 'w').write('\n'.join(lines))
print(len(lines) - 5, 'sounds')
